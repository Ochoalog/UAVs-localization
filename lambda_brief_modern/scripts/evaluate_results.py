#!/usr/bin/env python3
"""
Evaluation and Visualization Script for lambda-BRIEF Modern
Computes localization metrics (Mean Error, RMSE, StdDev, Max, Median)
and plots trajectory comparisons vs ground truth.
"""

import sys
import os
import argparse
import math
import numpy as np

def parse_args():
    parser = argparse.ArgumentParser(description="Evaluate lambda-BRIEF localization results")
    parser.add_argument("--results_dir", "-r", type=str, required=True,
                        help="Directory containing traj_estimated.txt and/or errors.txt")
    parser.add_argument("--gt", "-g", type=str, default=None,
                        help="Ground truth file (traj_truth.txt or GT2.txt)")
    parser.add_argument("--scale", "-s", type=float, default=0.188679245,
                        help="Pixel to meters scale factor (default: 0.188679245 for ADM)")
    parser.add_argument("--plot", "-p", action="store_true",
                        help="Generate matplotlib figures")
    parser.add_argument("--output_plot", "-o", type=str, default="evaluation_plots.png",
                        help="Output image path for plots")
    return parser.parse_args()

def load_errors_file(errors_path):
    """Loads errors.txt generated by lambda_brief_loc"""
    frames = []
    est_x, est_y, est_z = [], [], []
    gt_x, gt_y, gt_z = [], [], []
    pos_errors, yaw_errors = [], []

    with open(errors_path, "r") as f:
        header = f.readline()
        for line in f:
            parts = line.strip().split()
            if len(parts) >= 9:
                frames.append(int(parts[0]))
                est_x.append(float(parts[1]))
                est_y.append(float(parts[2]))
                est_z.append(float(parts[3]))
                gt_x.append(float(parts[4]))
                gt_y.append(float(parts[5]))
                gt_z.append(float(parts[6]))
                pos_errors.append(float(parts[7]))
                yaw_errors.append(float(parts[8]))

    return {
        "frames": np.array(frames),
        "est_x": np.array(est_x),
        "est_y": np.array(est_y),
        "est_z": np.array(est_z),
        "gt_x": np.array(gt_x),
        "gt_y": np.array(gt_y),
        "gt_z": np.array(gt_z),
        "pos_errors": np.array(pos_errors),
        "yaw_errors": np.array(yaw_errors)
    }

def print_metrics(data, scale):
    pos_err = data["pos_errors"]
    yaw_err = data["yaw_errors"]

    mean_pos = np.mean(pos_err)
    rmse_pos = np.sqrt(np.mean(pos_err**2))
    std_pos = np.std(pos_err)
    median_pos = np.median(pos_err)
    max_pos = np.max(pos_err)
    min_pos = np.min(pos_err)

    mean_yaw = np.mean(yaw_err)
    rmse_yaw = np.sqrt(np.mean(yaw_err**2))
    std_yaw = np.std(yaw_err)

    print("\n=======================================================")
    print("           lambda-BRIEF Evaluation Report              ")
    print("=======================================================")
    print(f"Total Evaluated Frames: {len(pos_err)}")
    print(f"Scale Factor:           {scale:.6f} m/pixel\n")
    print("Position Errors (Meters):")
    print(f"  Mean Error:           {mean_pos:.2f} m")
    print(f"  RMSE Error:           {rmse_pos:.2f} m")
    print(f"  Std Dev:              {std_pos:.2f} m")
    print(f"  Median Error:         {median_pos:.2f} m")
    print(f"  Min / Max Error:      {min_pos:.2f} m / {max_pos:.2f} m")
    print("\nOrientation Errors (Degrees):")
    print(f"  Mean Yaw Error:       {mean_yaw:.2f} deg")
    print(f"  RMSE Yaw Error:       {rmse_yaw:.2f} deg")
    print(f"  Std Dev Yaw:          {std_yaw:.2f} deg")
    print("=======================================================\n")

def generate_plots(data, output_path):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("[Warning] matplotlib is not installed; skipping plot generation.")
        return

    fig, axes = plt.subplots(2, 2, figsize=(14, 10))

    # 1. 2D Trajectory comparison
    ax_traj = axes[0, 0]
    ax_traj.plot(data["gt_x"], data["gt_y"], "g-o", label="Ground Truth", markersize=3, linewidth=1.5)
    ax_traj.plot(data["est_x"], data["est_y"], "r--s", label="lambda-BRIEF (Estimated)", markersize=3, linewidth=1.5)
    ax_traj.set_title("2D Trajectory Comparison (Map Pixels)")
    ax_traj.set_xlabel("Map X (px)")
    ax_traj.set_ylabel("Map Y (px)")
    ax_traj.grid(True, linestyle="--", alpha=0.6)
    ax_traj.legend()
    ax_traj.invert_yaxis()

    # 2. Position error vs Frame
    ax_err = axes[0, 1]
    ax_err.plot(data["frames"], data["pos_errors"], "b-", linewidth=1.5, label="Position Error (m)")
    ax_err.axhline(np.mean(data["pos_errors"]), color="r", linestyle="--", label=f"Mean: {np.mean(data['pos_errors']):.2f}m")
    ax_err.set_title("Position Error per Frame")
    ax_err.set_xlabel("Frame Index")
    ax_err.set_ylabel("Error (meters)")
    ax_err.grid(True, linestyle="--", alpha=0.6)
    ax_err.legend()

    # 3. Cumulative Distribution Function (CDF)
    ax_cdf = axes[1, 0]
    sorted_err = np.sort(data["pos_errors"])
    cdf = np.arange(1, len(sorted_err) + 1) / len(sorted_err)
    ax_cdf.plot(sorted_err, cdf, "k-", linewidth=2)
    ax_cdf.set_title("Cumulative Error Distribution (CDF)")
    ax_cdf.set_xlabel("Position Error (meters)")
    ax_cdf.set_ylabel("Cumulative Probability")
    ax_cdf.grid(True, linestyle="--", alpha=0.6)

    # 4. Yaw Error per Frame
    ax_yaw = axes[1, 1]
    ax_yaw.plot(data["frames"], data["yaw_errors"], "m-", linewidth=1.5, label="Yaw Error (deg)")
    ax_yaw.axhline(np.mean(data["yaw_errors"]), color="r", linestyle="--", label=f"Mean: {np.mean(data['yaw_errors']):.2f}°")
    ax_yaw.set_title("Yaw Error per Frame")
    ax_yaw.set_xlabel("Frame Index")
    ax_yaw.set_ylabel("Error (degrees)")
    ax_yaw.grid(True, linestyle="--", alpha=0.6)
    ax_yaw.legend()

    plt.tight_layout()
    plt.savefig(output_path, dpi=200)
    plt.close()
    print(f"[Plot] Saved evaluation figure to: {output_path}")

def main():
    args = parse_args()
    errors_file = os.path.join(args.results_dir, "errors.txt")

    if not os.path.exists(errors_file):
        print(f"Error: {errors_file} not found.")
        sys.exit(1)

    data = load_errors_file(errors_file)
    if len(data["pos_errors"]) == 0:
        print("Error: No error data found in errors.txt.")
        sys.exit(1)

    print_metrics(data, args.scale)

    if args.plot:
        out_plot = os.path.join(args.results_dir, args.output_plot)
        generate_plots(data, out_plot)

if __name__ == "__main__":
    main()
